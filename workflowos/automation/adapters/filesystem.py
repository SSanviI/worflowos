# workflowos/automation/adapters/filesystem.py
"""Real Windows Filesystem Automation Adapter.

Executes actual file and folder operations on Windows:
- File creation / identification
- File renaming
- File moving
- Directory creation
- Input directory scanning

All operations interact directly with the local operating system and return
real results or real error messages when files/paths are missing.
"""

import os
import shutil
from typing import Dict, Any, Tuple, Optional
from pathlib import Path
from .base import BaseAdapter

DEFAULT_TEST_INPUT = os.path.abspath(r"C:\WorkFlowOS_Test\Input")
DEFAULT_TEST_OUTPUT = os.path.abspath(r"C:\WorkFlowOS_Test\Output")


class FileSystemAdapter(BaseAdapter):
    """Executes real file system automation actions."""

    @classmethod
    def create_file(
        cls,
        db: Any,
        params: Dict[str, Any],
        context: Dict[str, Any]
    ) -> Tuple[bool, Any, Optional[str]]:
        """Create a real file on disk, or identify an already provided input file."""
        resolved = cls.resolve_params(params, context)
        file_path = resolved.get("file_path") or resolved.get("path") or context.get("file_path")

        # If a file already exists at the given path, identify it as input
        if file_path and os.path.exists(file_path):
            abs_path = os.path.abspath(file_path)
            context["file_path"] = abs_path
            context["file_name"] = os.path.basename(abs_path)
            context["file_dir"] = os.path.dirname(abs_path)
            return True, {
                "action": "IDENTIFY_FILE",
                "file_path": abs_path,
                "file_name": os.path.basename(abs_path),
                "status": "existing_input_file_identified"
            }, None

        content = resolved.get("content", "Generated by WorkFlowOS Automation Engine\n")

        if not file_path:
            # Check if input directory has pending files
            input_dir = resolved.get("input_dir") or DEFAULT_TEST_INPUT
            os.makedirs(input_dir, exist_ok=True)
            files = [os.path.join(input_dir, f) for f in os.listdir(input_dir) if os.path.isfile(os.path.join(input_dir, f))]
            if files:
                abs_path = os.path.abspath(files[-1])
                context["file_path"] = abs_path
                context["file_name"] = os.path.basename(abs_path)
                context["file_dir"] = input_dir
                return True, {
                    "action": "IDENTIFY_FILE",
                    "file_path": abs_path,
                    "file_name": os.path.basename(abs_path),
                    "status": "input_file_detected"
                }, None

            import datetime
            ts = datetime.datetime.now().strftime("%Y%m%d_%H%M%S")
            file_path = os.path.join(input_dir, f"workflowos_file_{ts}.txt")

        abs_path = os.path.abspath(file_path)
        parent_dir = os.path.dirname(abs_path)
        os.makedirs(parent_dir, exist_ok=True)

        try:
            with open(abs_path, "w", encoding="utf-8") as f:
                f.write(content)

            context["file_path"] = abs_path
            context["file_name"] = os.path.basename(abs_path)
            context["file_dir"] = parent_dir

            return True, {
                "action": "CREATE_FILE",
                "file_path": abs_path,
                "file_name": os.path.basename(abs_path),
                "size_bytes": os.path.getsize(abs_path),
                "status": "created_successfully"
            }, None
        except Exception as e:
            return False, None, f"Failed to create file at {abs_path}: {str(e)}"

    @classmethod
    def rename_file(
        cls,
        db: Any,
        params: Dict[str, Any],
        context: Dict[str, Any]
    ) -> Tuple[bool, Any, Optional[str]]:
        """Rename an existing file on disk."""
        resolved = cls.resolve_params(params, context)
        source_path = resolved.get("source_path") or resolved.get("file_path") or context.get("file_path")

        if not source_path:
            input_dir = resolved.get("input_dir") or DEFAULT_TEST_INPUT
            if os.path.exists(input_dir):
                files = [os.path.join(input_dir, f) for f in os.listdir(input_dir) if os.path.isfile(os.path.join(input_dir, f))]
                if files:
                    source_path = files[-1]

        if not source_path or not os.path.exists(source_path):
            return False, None, f"Source file for rename does not exist: {source_path}"

        source_abs = os.path.abspath(source_path)
        source_dir = os.path.dirname(source_abs)
        source_name = os.path.basename(source_abs)

        new_name = resolved.get("new_name") or resolved.get("target")
        if not new_name:
            name_part, ext = os.path.splitext(source_name)
            if not name_part.startswith("processed_"):
                new_name = f"processed_{name_part}{ext}"
            else:
                new_name = f"renamed_{name_part}{ext}"

        dest_abs = os.path.join(source_dir, new_name)

        try:
            if os.path.exists(dest_abs) and os.path.normcase(dest_abs) != os.path.normcase(source_abs):
                os.remove(dest_abs)

            os.rename(source_abs, dest_abs)

            context["file_path"] = dest_abs
            context["file_name"] = new_name
            context["old_file_name"] = source_name

            return True, {
                "action": "RENAME_FILE",
                "old_path": source_abs,
                "new_path": dest_abs,
                "old_name": source_name,
                "new_name": new_name,
                "status": "renamed_successfully"
            }, None
        except Exception as e:
            return False, None, f"Failed to rename file {source_abs} -> {dest_abs}: {str(e)}"

    @classmethod
    def move_file(
        cls,
        db: Any,
        params: Dict[str, Any],
        context: Dict[str, Any]
    ) -> Tuple[bool, Any, Optional[str]]:
        """Move an existing file on disk to a destination directory."""
        resolved = cls.resolve_params(params, context)
        source_path = resolved.get("source_path") or resolved.get("file_path") or context.get("file_path")

        if not source_path:
            input_dir = resolved.get("input_dir") or DEFAULT_TEST_INPUT
            if os.path.exists(input_dir):
                files = [os.path.join(input_dir, f) for f in os.listdir(input_dir) if os.path.isfile(os.path.join(input_dir, f))]
                if files:
                    source_path = files[-1]

        if not source_path or not os.path.exists(source_path):
            return False, None, f"Source file for move does not exist: {source_path}"

        source_abs = os.path.abspath(source_path)
        dest_dir = resolved.get("destination_dir") or resolved.get("target_dir") or DEFAULT_TEST_OUTPUT
        dest_dir_abs = os.path.abspath(dest_dir)
        os.makedirs(dest_dir_abs, exist_ok=True)

        file_name = os.path.basename(source_abs)
        dest_file_path = os.path.join(dest_dir_abs, file_name)

        try:
            if os.path.exists(dest_file_path):
                os.remove(dest_file_path)

            shutil.move(source_abs, dest_file_path)

            context["file_path"] = dest_file_path
            context["destination_path"] = dest_file_path
            context["moved_path"] = dest_file_path

            return True, {
                "action": "MOVE_FILE",
                "source": source_abs,
                "destination": dest_file_path,
                "status": "moved_successfully",
                "exists_at_destination": os.path.exists(dest_file_path)
            }, None
        except Exception as e:
            return False, None, f"Failed to move file from {source_abs} to {dest_file_path}: {str(e)}"

    @classmethod
    def create_directory(
        cls,
        db: Any,
        params: Dict[str, Any],
        context: Dict[str, Any]
    ) -> Tuple[bool, Any, Optional[str]]:
        resolved = cls.resolve_params(params, context)
        dir_path = resolved.get("dir_path") or resolved.get("path")
        if not dir_path:
            import datetime
            ts = datetime.datetime.now().strftime("%Y%m%d_%H%M%S")
            dir_path = os.path.join(DEFAULT_TEST_OUTPUT, f"folder_{ts}")

        abs_path = os.path.abspath(dir_path)
        try:
            os.makedirs(abs_path, exist_ok=True)
            context["dir_path"] = abs_path
            return True, {
                "action": "CREATE_DIRECTORY",
                "dir_path": abs_path,
                "status": "directory_created"
            }, None
        except Exception as e:
            return False, None, f"Failed to create directory {abs_path}: {str(e)}"

    @classmethod
    def delete_file(
        cls,
        db: Any,
        params: Dict[str, Any],
        context: Dict[str, Any]
    ) -> Tuple[bool, Any, Optional[str]]:
        resolved = cls.resolve_params(params, context)
        file_path = resolved.get("file_path") or context.get("file_path")
        if not file_path or not os.path.exists(file_path):
            return False, None, f"File to delete does not exist: {file_path}"

        try:
            os.remove(file_path)
            return True, {"action": "DELETE_FILE", "deleted_path": file_path}, None
        except Exception as e:
            return False, None, f"Failed to delete {file_path}: {str(e)}"
